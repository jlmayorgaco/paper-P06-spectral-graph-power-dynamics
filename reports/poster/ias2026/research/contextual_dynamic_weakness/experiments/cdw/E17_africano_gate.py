"""E17 Africano / PV material gate (prereg E17): search, do not fabricate."""

from __future__ import annotations

import json
import os
import re

import _infra as I

PATTERNS = [r"africano", r"hosting[ _-]?capacity", r"\bPVR\b", r"weak[ _-]?node", r"nodos[ _]?d[eé]biles"]
EXT = {".py", ".md", ".tex", ".bib", ".txt", ".json", ".csv", ".m", ".dss", ".xlsx", ".pdf", ".docx"}
SKIP = {".git", ".venv", "external", "node_modules", "__pycache__", "raw"}


def search():
    hits = []
    rx = re.compile("|".join(PATTERNS), re.I)
    for root, dirs, files in os.walk(I.REPO):
        dirs[:] = [d for d in dirs if d not in SKIP]
        for f in files:
            p = os.path.join(root, f)
            ext = os.path.splitext(f)[1].lower()
            name_hit = bool(rx.search(f))
            if ext not in EXT and not name_hit:
                continue
            text_hit = []
            if ext in {".py", ".md", ".tex", ".bib", ".txt", ".json", ".m", ".dss"}:
                try:
                    with open(p, encoding="utf-8", errors="ignore") as fh:
                        for k, line in enumerate(fh):
                            if rx.search(line):
                                text_hit.append((k + 1, line.strip()[:160]))
                                if len(text_hit) >= 5:
                                    break
                except OSError:
                    continue
            if name_hit or text_hit:
                hits.append({"path": os.path.relpath(p, I.REPO), "name_hit": name_hit, "lines": text_hit})
    return hits


REQUIRED = ["source document (thesis/paper) with methodology", "feeder data (network, loads)", "weak-node metric definition (PVR or other)",
            "PV placement rule", "voltage limits", "hosting-capacity method", "reported results to reproduce"]


def run():
    hits = search()
    I.atomic_write_json(I.RESULTS / "CDW_E17_search_hits.json", hits)
    pdfs = [h for h in hits if h["path"].lower().endswith((".pdf", ".docx")) and "africano" in h["path"].lower()]
    has_source = bool(pdfs)
    lines = ["# CDW Africano material: missing inputs (E17 gate)", "",
             "Date: 2026-09-12. Generated by `experiments/cdw/E17_africano_gate.py` from a repository search", "",
             f"Patterns: {PATTERNS}. Files scanned: text sources, bib, json/csv names, pdf/docx names. {len(hits)} hits.", ""]
    lines += ["## What was found", ""]
    for h in hits[:60]:
        ls = "; ".join(f"L{k}: {t}" for k, t in h["lines"][:2])
        lines.append(f"- `{h['path']}`{' (name)' if h['name_hit'] else ''}{': ' + ls if ls else ''}")
    lines += ["", "## Required inputs (prereg E17) and status", "", "| input | status |", "|---|---|"]
    for r in REQUIRED:
        lines.append(f"| {r} | {'FOUND (see above)' if (has_source and 'source' in r) else 'NOT FOUND'} |")
    gate_pass = False
    if not has_source:
        decision = ["**GATE E17: FAIL (inputs missing).** No Africano source document (thesis/paper PDF or DOCX) was found in",
                    "the repository, and therefore no verifiable feeder data, metric definition, placement rule, hosting-capacity",
                    "method or reported result table. Any hits above are indirect references (e.g. scripts naming a weak-node",
                    "reference set); a list of node labels is not a methodology and cannot be replicated exactly."]
    else:
        decision = ["**GATE E17: NOT PASSED (manual provenance review required).** A candidate source document was found",
                    "(listed above), but the preregistration requires every input to be verified and a separate replication",
                    "preregistration before any Africano computation; none exists in this campaign."]
    lines += ["", "## Decision", ""] + decision + [
              "", "Phases 18-21 (exact replication, PV coalitions, no-storage control/topology hosting, dynamic hosting) and",
              "GOLD-E / GOLD-F are **BLOCKED**. No generic feeder was substituted.", "",
              "To unblock: provide the source document (thesis PDF or paper), the feeder model and data exactly as used,",
              "and the reported rankings / hosting-capacity values; then preregister the replication."]
    I.atomic_write_text(I.DOCS / "CDW_AFRICANO_MISSING_INPUTS.md", "\n".join(lines) + "\n")
    gate = {"E17_pass": gate_pass, "n_hits": len(hits), "source_document_found": has_source}
    I.atomic_write_json(I.RESULTS / "CDW_E17_gates.json", gate)
    return gate


if __name__ == "__main__":
    print(json.dumps(run(), indent=1))
