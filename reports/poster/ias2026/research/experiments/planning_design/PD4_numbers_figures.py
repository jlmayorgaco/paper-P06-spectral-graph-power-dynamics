PART5 = P.ROOT.parents[2] / "papers" / "series_replacement_portfolios" / "part5_planning_design"
BLUE, ORANGE, GREEN, GRAY = "#1f5fa8", "#d95f02", "#1b9e77", "#6b6b6b"


def fmt(x, nd=2):
    return f"{x:.{nd}f}"


def numbers(v: dict) -> str:
    d1, d2 = v["PD1"], v["PD2"]
    r = d1["rates"]
    m = {}

    def frac(key, t="all"):
        k, n = r[key][t]
        return f"{k}/{n}"

    for x, tag in (("rc", "RC"), ("sc", "SC"), ("ad", "AD")):
        for c in ("S0", "S1", "SB"):
            m[f"pd{tag}{c}"] = frac(f"{x}_{c}")
            for t, tt in (("mild", "Mild"), ("medium", "Med"), ("severe", "Sev")):
                m[f"pd{tag}{c}{tt}"] = frac(f"{x}_{c}", t)
    m["pdADrate"] = fmt(d1["H_PD1a"]["adaptive_S0_rate"], 3)
    m["pdADsevRate"] = fmt(d1["H_PD1b"]["adaptive_S0_severe_rate"], 3)
    m["pdHa"] = d1["H_PD1a"]["verdict"].replace("_", " ")
    m["pdHb"] = d1["H_PD1b"]["verdict"].replace("_", " ")
    m["pdHc"] = d1["H_PD1c"]["verdict"].replace("_", " ")
    m["pdMcN"] = f"{d1['H_PD1c']['mcnemar_p_one_sided']:.1e}"
    m["pdAdOnly"] = str(d1["H_PD1c"]["adaptive_only"])
    m["pdRcOnly"] = str(d1["H_PD1c"]["rc_only"])
    ds = d1["descriptive"]
    m["pdRhoNorm"] = fmt(ds["spearman_change_norm_vs_alpha_IA_successes"])
    m["pdBoundFrac"] = fmt(ds["bound_active_fraction"])
    m["pdBoundFracFail"] = fmt(ds["bound_active_fraction_failures"]) if np.isfinite(ds["bound_active_fraction_failures"]) else "---"
    for t, tt in (("mild", "Mild"), ("medium", "Med"), ("severe", "Sev")):
        val = ds["median_change_norm_by_tercile"][t]
        m[f"pdNorm{tt}"] = fmt(val) if np.isfinite(val) else "---"
    m["pdRepro"] = f"{d1['max_repro_err']:.1e}"
    m["pdGoldD"] = d2["GOLD_D_census"].split(" ")[0].replace("_", " ")
    lines = ["% generated by experiments/planning_design/PD4_numbers_figures.py - do not edit"]
    lines += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in sorted(m.items())]
    return "\n".join(lines) + "\n"


def fig_pd1(table: pd.DataFrame, out: Path):
    fig, axs = plt.subplots(1, 2, figsize=(7.0, 2.4))
    ax = axs[0]
    terc = ["mild", "medium", "severe"]
    x = np.arange(3)
    for k, (col, lab, c) in enumerate((("rc_S0", "frozen retune", GRAY), ("ad_S0", "adaptive retune", BLUE), ("sc_S0", "25 % condenser", GREEN))):
        vals = [table[table.tercile == t][col].mean() for t in terc]
        ax.bar(x + (k - 1) * 0.27, vals, 0.26, color=c, label=lab)
    ax.set_xticks(x)
    ax.set_xticklabels(["mild", "medium", "severe"])
    ax.set_ylim(0, 1.05)
    ax.set_ylabel("transversely stable (S0)")
    ax.legend(fontsize=6, loc="lower left")
    ax = axs[1]
    ok = table[table.ad_S0]
    bad = table[~table.ad_S0]
    ax.scatter(ok.alpha_IA_e35, ok.change_norm, s=8, color=BLUE, lw=0, label="adaptive: stable")
    ax.scatter(bad.alpha_IA_e35, bad.change_norm, s=12, color=ORANGE, marker="x", lw=0.8, label="adaptive: not stable")
    ax.axhline(np.sqrt(5) * np.log(8.0), color=GRAY, lw=0.6, ls=":")
    ax.set_xlabel(r"E35 severity $\alpha_{\rm IA}$ [s$^{-1}$]")
    ax.set_ylabel(r"retune norm $\|v\|$")
    ax.legend(fontsize=6)
    fig.tight_layout()
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)


def fig_pd2(out: Path):
    import pd2_census_design as PD2

    fig, axs = plt.subplots(1, 2, figsize=(7.0, 2.4), sharey=True)
    for ax, tg in zip(axs, ("T2", "T4"), strict=True):
        for task in PD2.tasks():
            if task["target"] != tg:
                continue
            p = PD2.TASK_DIR / f"{PD2.task_name(task)}.json"
            if not p.exists():
                continue
            r = json.loads(p.read_text(encoding="utf-8"))
            h = r.get("history") or []
            if not h:
                continue
            key = "phi" if task["method"] == "plan" else "alpha_T"
            y = [max(abs(x[key]), 1e-3) * np.sign(x[key]) for x in h if np.isfinite(x[key])]
            ls = "-" if task["method"] == "plan" else "--"
            c = {"control": BLUE, "topology": ORANGE, "joint": GREEN}[task["family"]]
            ax.plot(range(len(y)), y, ls, color=c, lw=1, label=f"{task['family']}, {task['method']}")
        ax.set_yscale("symlog", linthresh=1e-2)
        ax.axhline(0, color=GRAY, lw=0.6)
        ax.set_xlabel("iteration")
        ax.set_title(f"{tg} (nine candidates, 512 portfolios)", fontsize=7)
    axs[0].set_ylabel(r"merit: $\Phi$ (plan), $\alpha_T$ (single) [s$^{-1}$]")
    axs[1].legend(fontsize=5.5, ncol=2)
    fig.tight_layout()
    fig.savefig(out, bbox_inches="tight")
    plt.close(fig)


def main() -> int:
    v = json.loads((P.RESULTS / "PD_VERDICTS.json").read_text(encoding="utf-8"))
    (PART5 / "figures").mkdir(parents=True, exist_ok=True)
    (PART5 / "pd_numbers.tex").write_text(numbers(v), encoding="utf-8")
    table = pd.read_csv(P.RESULTS / "PD1" / "PD1_table.csv")
    fig_pd1(table, PART5 / "figures" / "fig_pd1_adaptive.pdf")
    fig_pd1(table, P.out_dir("PD1") / "fig_pd1_adaptive.png")
    if "pd2" in sys.argv[1:] or not sys.argv[1:]:
        fig_pd2(PART5 / "figures" / "fig_pd2_design.pdf")
        fig_pd2(P.out_dir("PD2") / "fig_pd2_design.png")
    print("written", PART5)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
