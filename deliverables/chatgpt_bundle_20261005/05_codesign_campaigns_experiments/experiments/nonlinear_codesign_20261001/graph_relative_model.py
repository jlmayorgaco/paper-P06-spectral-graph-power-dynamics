"""Exact co-rotating network ports; graph angle differences retain modal correlations.

Generated by build_graph_relative_model.py. All device states and nonlinearities
remain. The AC operator must commute exactly with planar rotations.
"""
import numpy as np
import math
import mpmath as mp
import coupled_dq_model as md
from coupled_dq_model import Jet,sf,lower,upper,add,neg,mul,mm,inverse_enclosure,magnitude,positive_product,up,down


class GraphRelativeModel(md.Model):
    def __init__(self,*args,**kwargs):
        super().__init__(*args,**kwargs)
        J=np.kron(np.eye(39),np.array([[0.,-1.],[1.,0.]]))
        assert np.array_equal(self.Y@J,J@self.Y)
        self.position={int(raw):j for j,raw in enumerate(self.keep)}
        self.support=None;self.angle_cache={}

    def set_support(self,Ti,groups,radii):
        self.support=(Ti,groups,radii);self.angle_cache={}

    def angle_difference(self,ia,ib,x):
        delta=x[ia]-x[ib]
        if not isinstance(delta,Jet) or self.support is None:return delta
        key=(ia,ib)
        if key not in self.angle_cache:
            Ti,groups,radii=self.support
            row=np.zeros((1,self.nx))
            if ia in self.position:row[0,self.position[ia]]+=1.
            if ib in self.position:row[0,self.position[ib]]-=1.
            tangent=mm((row,row),Ti);coeff=magnitude(tangent)[0]
            widths=np.array([up(np.sqrt(up(np.sum(coeff[g]**2)*(1+8*len(g)*np.finfo(float).eps)))) for g in groups])
            radius=float(positive_product(widths[None,:],radii[:,None])[0,0])
            center=add((self.x0[ia],self.x0[ia]),(-self.x0[ib],-self.x0[ib]))
            ca=self.center[self.position[ia]] if ia in self.position else 0.
            cb=self.center[self.position[ib]] if ib in self.position else 0.
            center=add(center,add((ca,ca),(-cb,-cb)))
            self.angle_cache[key]=(down(center[0]-radius),up(center[1]+radius),widths,radius)
        lo,hi,_,_=self.angle_cache[key]
        val=(max(lo,delta.v[0]),min(hi,delta.v[1]));assert val[0]<=val[1]
        return Jet.from_parts(val,delta.d)


    def prepare_local_network(self,coeff,w):
        self.local_coeff=coeff;self.local_w=w

    def local_voltage(self,b,angle_idx,x,sources):
        alpha=x[angle_idx];c=sf("cos",alpha);s=sf("sin",alpha)
        source=[];w=self.local_w
        for bus in range(39):
            source.extend([c*w[2*bus]+s*w[2*bus+1],-s*w[2*bus]+c*w[2*bus+1]])
        for a,source_angle,qr,qi in sources:
            delta=self.angle_difference(source_angle,angle_idx,x)
            c=sf("cos",delta);s=sf("sin",delta)
            source[2*a]=source[2*a]+c*qr-s*qi
            source[2*a+1]=source[2*a+1]+s*qr+c*qi
        local=self.voltage(self.local_coeff,source)
        return local[2*b],local[2*b+1]

    def evaluate(self, z, w):
        interval = isinstance(z[0], Jet)
        C = Jet if interval else (mp.iv.mpf if hasattr(z[0], "_mpi_") else float)
        z = [a+C(b) for a,b in zip(z,self.center)]
        d = self.raw
        x = [C(v) for v in self.x0]
        for k, idx in enumerate(self.keep):
            x[idx] = x[idx] + z[k]
        source = [C(v) if not isinstance(v, Jet) else v for v in w[:78]]
        coeff = []; sgaux = []; local_sources = []
        for i, ix in enumerate(self.sg):
            p = {k: (v if isinstance(v, bool) else C(v)) for k,v in d["sg_parameters"][i].items()}
            pq,pd,ed,eq,omega,delta = [x[k] for k in ix[-6:]]
            assert lower(omega) > 0
            gd1 = (p["xdpp"]-p["xls"])/(p["xdp"]-p["xls"])
            gq1 = (p["xqpp"]-p["xls"])/(p["xqp"]-p["xls"])
            cd = gd1*eq+(1-gd1)*pd; cq = -gq1*ed+(1-gq1)*pq
            sn = sf("sin", delta); cs = sf("cos", delta)
            scale = (1-C(d["rho"][i])) * p["rating_mva"]/p["system_base_mva"]
            coeff.append(scale/(omega*p["xdpp"]))
            j = 2*(i+29)
            source[j] = source[j] + scale/p["xdpp"]*(sn*cd+cs*cq)
            source[j+1] = source[j+1] + scale/p["xdpp"]*(-cs*cd+sn*cq)
            gf = self.gf[i]
            cg=sf("cos",x[gf[2]]);sg=sf("sin",x[gf[2]])
            source[j] = source[j] + C(d["rho"][i])*(cg*x[gf[6]]-sg*x[gf[5]])
            source[j+1] = source[j+1] + C(d["rho"][i])*(sg*x[gf[6]]+cg*x[gf[5]])
            local_sources.extend([(i+29,ix[-1],scale/p["xdpp"]*cq,-scale/p["xdpp"]*cd),
                                  (i+29,gf[2],C(d["rho"][i])*x[gf[6]],C(d["rho"][i])*x[gf[5]])])
            sgaux.append((p,pq,pd,ed,eq,omega,cd,cq,sn,cs,gd1,gq1))
        v = self.voltage(coeff, source)
        self.prepare_local_network(coeff,w)
        nu = C(d["sg_parameters"][-1]["omega_base"])*(x[self.ig-1]-C(d["sg_parameters"][-1]["omega_frame"]))
        dx = [C(0.) for _ in x]
        for i, ix in enumerate(self.sg):
            p,pq,pd,ed,eq,omega,cd,cq,sn,cs,gd1,gq1 = sgaux[i]
            ur,ui = v[2*(i+29):2*(i+30)]
            vq,minus_vd = self.local_voltage(i+29,ix[-1],x,local_sources)
            vd = -minus_vd
            id_ = cd/p["xdpp"]-vq/(omega*p["xdpp"])
            iq = cq/p["xqpp"]+vd/(omega*p["xqpp"])
            gd2 = (p["xdp"]-p["xdpp"])/(p["xdp"]-p["xls"])**2
            gq2 = (p["xqp"]-p["xqpp"])/(p["xqp"]-p["xls"])**2
            if p["controlled"]:
                xg1,xg2,vfb,vfout,vr,vm = [x[k] for k in ix[:6]]
                assert lower(xg1) > upper(p["gov_vmin"]) and upper(xg1) < lower(p["gov_vmax"])
                assert lower(vr) > upper(p["avr_vr_min"]) and upper(vr) < lower(p["avr_vr_max"])
                assert lower(vfout) > 0
                a = sf("sqrt", p["avr_se1"]*p["avr_e1"]/(p["avr_se2"]*p["avr_e2"]))
                thresh = p["avr_e2"]-(p["avr_e1"]-p["avr_e2"])/(a-1)
                bc = p["avr_se2"]*p["avr_e2"]*(a-1)**2/(p["avr_e1"]-p["avr_e2"])**2
                if upper(vfout) < lower(thresh):
                    ceil = C(0.)
                elif lower(vfout) > upper(thresh):
                    ceil = bc*(vfout-thresh)**2
                else:
                    raise ValueError("AVR saturation branch crossed by interval domain")
                vfoutdot = (vr-ceil-p["avr_ke"]*vfout)/p["avr_te"]
                vfbdot = (p["avr_kf"]*vfoutdot-vfb)/p["avr_tf"]
                vrdot = (p["avr_ka"]*(p["avr_vref"]-vm-vfb)-vr)/p["avr_ta"]
                vmdot = (sf("sqrt", vd**2+vq**2)-vm)/p["avr_tr"]
                xg1dot = ((p["gov_p_ref"]-(omega-p["gov_omega_ref"]))/p["gov_r"]-xg1)/p["gov_t1"]
                xg2dot = (xg1+p["gov_t2"]*xg1dot-xg2)/p["gov_t3"]
                taum = (xg2-p["gov_dt"]*(omega-p["gov_omega_ref"]))/omega
                vf = vfout
                for j,val in zip(ix[:6], (xg1dot,xg2dot,vfbdot,vfoutdot,vrdot,vmdot)):
                    dx[j] = val
            else:
                taum = p["tau_m_set"]; vf = p["vf_set"]
            taue = (cd*vd+cq*vq)/(omega*p["xdpp"])
            omdot = (taum-taue-p["damping"]*(omega-1))/(2*p["inertia"])
            eqdot = (-eq-(p["xd"]-p["xdp"])*(id_-gd2*pd-(1-gd1)*id_+gd2*eq)+vf)/p["tdp"]
            eddot = (-ed+(p["xq"]-p["xqp"])*(iq-gq2*pq-(1-gq1)*iq-gq2*ed))/p["tqp"]
            pddot = (-pd+eq-(p["xdp"]-p["xls"])*id_)/p["tdpp"]
            pqdot = (-pq-ed-(p["xqp"]-p["xls"])*iq)/p["tqpp"]
            deldot = p["omega_base"]*(omega-p["omega_frame"])-nu
            for j,val in zip(ix[-6:], (pqdot,pddot,eddot,eqdot,omdot,deldot)):
                dx[j] = val

            ixg = self.gf[i]
            gammaq,gammad,theta,om,xi,iqg,idg,vdi,vdc = [x[k] for k in ixg]
            assert lower(vdc) > 0
            gp = {k: C(v) for k,v in d["gfl_parameters"][i].items()}
            c = sf("cos",theta); s = sf("sin",theta)
            ud,uq = self.local_voltage(i+29,ixg[2],x,local_sources)
            edg = (vdc-gp["Vdc"])*gp["dc_kp"]+vdi-idg; eqg = gp["iset_q"]-iqg
            vid = gp["cc_kp"]*edg+gp["cc_ki"]*gammad
            viq = gp["cc_kp"]*eqg+gp["cc_ki"]*gammaq
            e = uq
            fg = [eqg,edg,om-nu,(xi+C(d["Kp"][i])*e-om)/gp["pll_tau"],C(d["Ki"][i])*e,
                  gp["omega_base"]/gp["Xf"]*(viq-uq-gp["Rf"]*iqg)-(gp["omega_base"]*gp["omega_frame"]+om)*idg,
                  gp["omega_base"]/gp["Xf"]*(vid-ud-gp["Rf"]*idg)+(gp["omega_base"]*gp["omega_frame"]+om)*iqg,
                  (vdc-gp["Vdc"])*gp["dc_ki"],(gp["Pdc"]+w[78+i]-vid*idg-viq*iqg)/(gp["Cdc"]*vdc)]
            for j,val in zip(ixg,fg): dx[j] = val
        out = [dx[j] for j in self.keep]+[C(0.) for _ in range(78)]
        freq=[];rocof=[]
        for b in range(39):
            c = sf("cos",C(d["phase0"][b])); s = sf("sin",C(d["phase0"][b]))
            ur,ui = v[2*b:2*b+2]; den = c*ur+s*ui
            assert lower(den) > 0
            ph = sf("atan",(c*ui-s*ur)/den)
            eta = z[len(self.keep)+b]; chi = z[len(self.keep)+39+b]
            ff = (ph-eta)/(C(2*math.pi)*C(d["tau_f"]))
            rr = (ff-chi)/C(d["tau_r"])
            out[len(self.keep)+b] = (ph-eta)/C(d["tau_f"])-nu
            out[len(self.keep)+39+b] = rr
            freq.append(ff);rocof.append(rr)
        return out,v,freq,rocof
