"""Generate an explicit dq-coordinate backend while preserving frozen RI results.

Every replacement is checked once. The generated files contain ordinary readable
equations, not runtime source rewriting. The original backend is unchanged.
"""
from pathlib import Path

D=Path(__file__).resolve().parent
def replace(text,old,new):
    assert text.count(old)==1,old[:100]
    return text.replace(old,new)

py=(D/"coupled_interval_model.py").read_text(encoding="utf-8")
py=replace(py,'coupled_network_contract"','coupled_dq_contract"')
py=replace(py,
'            source[j] = source[j] + C(d["rho"][i])*x[gf[6]]\n            source[j+1] = source[j+1] + C(d["rho"][i])*x[gf[5]]',
'''            cg=sf("cos",x[gf[2]]);sg=sf("sin",x[gf[2]])
            source[j] = source[j] + C(d["rho"][i])*(cg*x[gf[6]]-sg*x[gf[5]])
            source[j+1] = source[j+1] + C(d["rho"][i])*(sg*x[gf[6]]+cg*x[gf[5]])''')
py=replace(py,'gammaq,gammad,theta,om,xi,ifi,ifr,vdi,vdc = [x[k] for k in ixg]',
              'gammaq,gammad,theta,om,xi,iqg,idg,vdi,vdc = [x[k] for k in ixg]')
py=replace(py,'            idg = c*ifr+s*ifi; iqg = -s*ifr+c*ifi',
              '            ud = c*ur+s*ui; uq = -s*ur+c*ui')
py=replace(py,'            e = -s*ur+c*ui','            e = uq')
py=replace(py,
'''                  gp["omega_base"]/gp["Xf"]*(s*vid+c*viq-ui-gp["Rf"]*ifi-gp["omega_frame"]*gp["Xf"]*ifr)-nu*ifr,
                  gp["omega_base"]/gp["Xf"]*(c*vid-s*viq-ur-gp["Rf"]*ifr+gp["omega_frame"]*gp["Xf"]*ifi)+nu*ifi,''',
'''                  gp["omega_base"]/gp["Xf"]*(viq-uq-gp["Rf"]*iqg)-(gp["omega_base"]*gp["omega_frame"]+om)*idg,
                  gp["omega_base"]/gp["Xf"]*(vid-ud-gp["Rf"]*idg)+(gp["omega_base"]*gp["omega_frame"]+om)*iqg,''')
py=py.replace('"""Full SG/GFL AC DAE in an exact rotating chart, with interval first derivatives.',
'''"""Full SG/GFL AC DAE with exact local dq GFL-current coordinates.

Generated by build_coupled_dq_backend.py. GFL indices 5/6 hold iq/id (zero based),
not global imaginary/real current. The rotating-chart frequency cancels exactly
from the dq current equations; the physical PLL frequency remains.''')
(D/"coupled_dq_model.py").write_text(py,encoding="utf-8")

jl=(D/"export_coupled_contract_model.jl").read_text(encoding="utf-8")
globalfun=jl[jl.index("function full_rhs"):jl.index("\nz=zeros(nx)")].replace("function full_rhs","function global_rhs",1)
jl=replace(jl,'"coupled_network_contract"','"coupled_dq_contract"')
jl=replace(jl,'ig=last(m.sgidx[end]);',
'''xbase=copy(m.x0)
for ix in m.gfidx
    sn,cs=sincos(m.x0[ix[3]]);ii=m.x0[ix[6]];ir=m.x0[ix[7]]
    xbase[ix[6]]=-sn*ir+cs*ii;xbase[ix[7]]=cs*ir+sn*ii
end
ig=last(m.sgidx[end]);''')
jl=replace(jl,'x=T.(m.x0);x[keep].+=view(z,1:length(keep))','x=T.(xbase);x[keep].+=view(z,1:length(keep))')
jl=replace(jl,'ix=m.gfidx[i];hh[vi].+=m.rho[i].*x[ix[[7,6]]]',
'''ix=m.gfidx[i];sn,cs=sincos(x[ix[3]])
        hh[vi].+=m.rho[i].*[cs*x[ix[7]]-sn*x[ix[6]],sn*x[ix[7]]+cs*x[ix[6]]]''')
jl=replace(jl,
'''        dx[ix].=R.gfl_rhs(view(x,ix),u,pp,m.kp[i],m.ki[i],:physical_supply)
        dx[ix[3]]-=nu;dx[ix[6]]-=nu*x[ix[7]];dx[ix[7]]+=nu*x[ix[6]]
        dx[ix[9]]+=w[78+i]/(pp.Cdc*x[ix[9]])''',
'''        gq,gd,theta,om,xi,iq,id,vdi,vdc=x[ix];sn,cs=sincos(theta)
        ud=cs*u[1]+sn*u[2];uq=-sn*u[1]+cs*u[2]
        ed=(vdc-pp.Vdc)*pp.dc_kp+vdi-id;eq=pp.iset_q-iq
        vid=pp.cc_kp*ed+pp.cc_ki*gd;viq=pp.cc_kp*eq+pp.cc_ki*gq
        dx[ix].=[eq,ed,om-nu,(xi+m.kp[i]*uq-om)/pp.pll_tau,m.ki[i]*uq,
                 pp.omega_base/pp.Xf*(viq-uq-pp.Rf*iq)-(pp.omega_base*pp.omega_frame+om)*id,
                 pp.omega_base/pp.Xf*(vid-ud-pp.Rf*id)+(pp.omega_base*pp.omega_frame+om)*iq,
                 (vdc-pp.Vdc)*pp.dc_ki,(pp.Pdc+w[78+i]-vid*id-viq*iq)/(pp.Cdc*vdc)]''')
jl=replace(jl,'"x0"=>m.x0','"x0"=>xbase')
jl=replace(jl,'\nz=zeros(nx);', '\n'+globalfun+'\nz=zeros(nx);')
jl=replace(jl,'    zz=1e-5.*randn(rng,nx);ww=1e-5.*randn(rng,88);r=full_rhs(zz,ww)',
'''    zz=1e-5.*randn(rng,nx);ww=1e-5.*randn(rng,88);r=full_rhs(zz,ww)
    xq=copy(xbase);xq[keep].+=zz[1:length(keep)];xg=copy(xq)
    for ix in m.gfidx
        sn,cs=sincos(xq[ix[3]]);iq=xq[ix[6]];id=xq[ix[7]]
        xg[ix[6]]=sn*id+cs*iq;xg[ix[7]]=cs*id-sn*iq
    end
    zr=vcat(xg[keep]-m.x0[keep],zz[length(keep)+1:end]);gr=global_rhs(zr,ww)
    fx=zeros(length(xbase));fx[keep].=gr.out[1:length(keep)]
    for ix in m.gfidx
        sn,cs=sincos(xq[ix[3]]);di=fx[ix[6]];dr=fx[ix[7]];rate=fx[ix[3]]
        fx[ix[6]]=-sn*dr+cs*di-xq[ix[7]]*rate
        fx[ix[7]]=cs*dr+sn*di+xq[ix[6]]*rate
    end
    mapped=vcat(fx[keep],gr.out[length(keep)+1:end])
    err=norm(mapped-r.out,Inf);@assert err<1e-6
    global max_mapping_error=max(max_mapping_error,err)''')
jl=replace(jl,'rng=MersenneTwister(20261002);rows=NamedTuple[]',
              'rng=MersenneTwister(20261002);rows=NamedTuple[];max_mapping_error=0.')
jl=replace(jl,'"model_sha256"=>bytes2hex(sha256(read(joinpath(OUT,"model.toml"))))))',
              '"max_global_coordinate_mapping_error"=>max_mapping_error,\n       "model_sha256"=>bytes2hex(sha256(read(joinpath(OUT,"model.toml"))))))')
jl=replace(jl,'println("EXPORTED_FULL_NETWORK model and 30 independent probes")',
              'println("EXPORTED_DQ_NETWORK; mapped global-coordinate error ",max_mapping_error)')
(D/"export_coupled_dq_model.jl").write_text(jl,encoding="utf-8")

audit=(D/"audit_coupled_interval_model.py").read_text(encoding="utf-8")
audit=audit.replace("from coupled_interval_model import", "from coupled_dq_model import")
audit=audit.replace('"coupled_interval_model.py"','"coupled_dq_model.py"')
(D/"audit_coupled_dq_model.py").write_text(audit,encoding="utf-8")
refine=(D/"refine_coupled_center.py").read_text(encoding="utf-8")
refine=refine.replace("from coupled_interval_model import", "from coupled_dq_model import")
refine=refine.replace('"coupled_interval_model.py"','"coupled_dq_model.py"')
(D/"refine_coupled_dq_center.py").write_text(refine,encoding="utf-8")
print("Generated explicit dq model, Julia mapping exporter, and audits; RI backend untouched.")
